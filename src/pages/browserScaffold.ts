// Turn a reverse-engineering snapshot into a runnable starter scaffold.
//
// browser_reverse_engineer already extracts the design tokens, layout outline and
// observed API surface. This module renders that into concrete files (index.html,
// styles.css, README.md, and an api.md endpoint map) so "clone this site" ends in
// real code the user can open, not just a description.
//
// D1: Static HTML/CSS scaffold, NOT a framework project.
//     Reason: a framework choice (React/Vue/Next) is the user's call and would need
//     a toolchain; a single static page runs by double-clicking and is a truthful
//     starting point for any stack. Cost: no interactivity generated.
//     Escape hatch: the agent can follow up with framework-specific edits.
// D2: Only sanitized, bounded data reaches the files (see clamp/escape helpers).
//     Reason: snapshot fields come from an untrusted page; unescaped text injected
//     into HTML/CSS would be an injection vector and could produce broken output.

import type { ReverseSnapshot } from './browserReverseEngineer';
import type { ApiEndpoint } from './browserReverseEngineer';

export interface ScaffoldFile { path: string; content: string }

// A hostile page can set title/heading to anything; neutralize HTML metacharacters.
export function escapeHtml(input: unknown): string {
  return String(input ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// CSS values must not break out of the declaration; allow only a safe charset.
export function sanitizeCssValue(input: unknown, fallback = 'inherit'): string {
  const raw = String(input ?? '').trim();
  if (!raw) return fallback;
  // Reject anything with braces, semicolons, at-rules, or url()/expression payloads.
  if (/[{}<>;@]|url\s*\(|expression\s*\(|javascript:/i.test(raw)) return fallback;
  return raw.slice(0, 120);
}

// A file/folder-safe slug for the project name derived from the page host.
export function slugForSnapshot(snapshot: ReverseSnapshot): string {
  let host = 'site';
  try { host = new URL(String(snapshot?.url || '')).hostname || 'site'; } catch { /* keep default */ }
  const slug = host.replace(/^www\./, '').replace(/[^a-z0-9]+/gi, '-').replace(/^-+|-+$/g, '').toLowerCase();
  return slug || 'site';
}

function bodyTokens(snapshot: ReverseSnapshot): { bg: string; fg: string; font: string } {
  const colors = snapshot?.colors || {};
  const fonts = snapshot?.fonts || {};
  return {
    bg: sanitizeCssValue(colors.body?.bg, '#ffffff'),
    fg: sanitizeCssValue(colors.body?.fg, '#111111'),
    font: sanitizeCssValue(fonts.body, 'system-ui, sans-serif'),
  };
}

function renderCss(snapshot: ReverseSnapshot): string {
  const { bg, fg, font } = bodyTokens(snapshot);
  const header = snapshot?.colors?.header || {};
  const button = snapshot?.colors?.button || {};
  const link = snapshot?.colors?.link || {};
  return `:root {
  --bg: ${bg};
  --fg: ${fg};
  --font: ${font};
  --header-bg: ${sanitizeCssValue(header.bg, 'var(--bg)')};
  --header-fg: ${sanitizeCssValue(header.fg, 'var(--fg)')};
  --button-bg: ${sanitizeCssValue(button.bg, '#2563eb')};
  --button-fg: ${sanitizeCssValue(button.fg, '#ffffff')};
  --link-fg: ${sanitizeCssValue(link.fg, '#2563eb')};
}
* { box-sizing: border-box; }
body { margin: 0; background: var(--bg); color: var(--fg); font-family: var(--font); line-height: 1.5; }
header, .site-header { background: var(--header-bg); color: var(--header-fg); padding: 1rem 1.5rem; }
main { max-width: 960px; margin: 0 auto; padding: 2rem 1.5rem; }
a { color: var(--link-fg); }
button, .btn { background: var(--button-bg); color: var(--button-fg); border: 0; padding: 0.6rem 1rem; border-radius: 6px; cursor: pointer; }
section { margin: 2rem 0; }
`;
}

function renderHtml(snapshot: ReverseSnapshot): string {
  const title = escapeHtml(snapshot?.title || 'Cloned Site');
  const headings = (snapshot?.outline || [])
    .filter((line) => /^\s*h[12]:/i.test(line))
    .slice(0, 12)
    .map((line) => {
      const m = line.match(/^\s*(h[12]):\s*(.*)$/i);
      if (!m) return '';
      return `      <${m[1].toLowerCase()}>${escapeHtml(m[2])}</${m[1].toLowerCase()}>`;
    })
    .filter(Boolean);
  const bodyInner = headings.length
    ? headings.join('\n')
    : '      <h1>' + title + '</h1>\n      <p>Scaffold generated by BBARIT Browser reverse-engineering.</p>';
  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <link rel="stylesheet" href="./styles.css" />
  </head>
  <body>
    <header class="site-header"><strong>${title}</strong></header>
    <main>
${bodyInner}
    </main>
    <script src="./app.js"></script>
  </body>
</html>
`;
}

function renderApiDoc(endpoints: ApiEndpoint[]): string {
  if (!endpoints.length) return '# API endpoints\n\n(None observed. Interact with the source site so its API calls are captured, then re-run.)\n';
  const rows = endpoints.map((e) => `| ${e.method} | \`${e.origin}${e.path}\` | ${e.count} | ${e.statuses.join(', ') || '-'} |`);
  return `# API endpoints (observed)\n\n| Method | Path | Calls | Statuses |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n`;
}

function renderReadme(snapshot: ReverseSnapshot, slug: string, endpoints: ApiEndpoint[]): string {
  const stack = [...(snapshot?.frameworks || [])];
  if (snapshot?.generator) stack.push(snapshot.generator);
  return `# ${slug} (reverse-engineered scaffold)\n\n`
    + `Generated by BBARIT Browser from ${snapshot?.url || '(unknown URL)'}.\n\n`
    + `## Detected stack\n${stack.length ? stack.map((s) => `- ${s}`).join('\n') : '- (no framework fingerprints detected)'}\n\n`
    + `## Files\n- \`index.html\` — page shell with the observed headings\n- \`styles.css\` — design tokens (colors/fonts) sampled from the source\n- \`app.js\` — empty entry point for your logic\n- \`api.md\` — ${endpoints.length} observed API endpoint(s)\n\n`
    + `## Run\nOpen \`index.html\` in a browser, or serve the folder with any static server.\n\n`
    + `> This is a faithful STARTING point, not a pixel-perfect copy. Interactivity and framework wiring are yours to add.\n`;
}

// Build the full scaffold. `baseDir` is prefixed to every path (e.g. "clone-example-com").
export function buildScaffold(snapshot: ReverseSnapshot, endpoints: ApiEndpoint[] = [], baseDir?: string): ScaffoldFile[] {
  const slug = slugForSnapshot(snapshot);
  const dir = (baseDir && baseDir.trim() ? baseDir.trim() : `clone-${slug}`).replace(/[/\\]+$/, '');
  const p = (name: string) => `${dir}/${name}`;
  return [
    { path: p('index.html'), content: renderHtml(snapshot) },
    { path: p('styles.css'), content: renderCss(snapshot) },
    { path: p('app.js'), content: '// Entry point for the reverse-engineered scaffold. Add your logic here.\n' },
    { path: p('api.md'), content: renderApiDoc(endpoints) },
    { path: p('README.md'), content: renderReadme(snapshot, slug, endpoints) },
  ];
}
