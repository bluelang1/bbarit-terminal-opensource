export type TsLang = 'en' | 'ko';

export const tsLang = (locale: string): TsLang => (locale === 'ko' ? 'ko' : 'en');

export function fmt(text: string, vars?: Record<string, string | number | undefined>): string {
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k]))) : text;
}

export type TsT = (key: TsKey, vars?: Record<string, string | number | undefined>) => string;

/** The translator for one locale. */
export function makeT(locale: string): TsT {
  const lang = tsLang(locale);
  return (key, vars) => fmt((lang === 'ko' ? ko[key] : undefined) ?? en[key] ?? String(key), vars);
}

export function stateLabel(locale: string, s: DisplayState | 'stale'): string {
  return STATE_LABEL[tsLang(locale)][s];
}

export function eventVerb(locale: string, action: string): string {
  return EVENT_VERB[tsLang(locale)][action] ?? action;
}

export function postKindLabel(locale: string, kind: string): string {
  return POST_KIND[tsLang(locale)][kind] ?? kind;
}

